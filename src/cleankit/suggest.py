"""Turn a profile into a starter pipeline and rule set.

``suggest(df)`` profiles the raw frame and writes down what a careful analyst
would do next:

* a ``steps.yaml`` that renames headers, trims whitespace, parses the types
  the profiler inferred, merges spelling variants of categories onto one
  canonical spelling, standardizes emails / phones / names / addresses,
  flags outliers, and deduplicates on the detected identifier;
* a ``rules.yaml`` that asserts what the cleaned data should look like:
  ``not_null`` for complete columns, ``unique`` + ``dtype`` for identifiers,
  ``allowed`` for low-cardinality categories, email and E.164 regexes, numeric
  ranges from the observed quartiles, and date-order checks that held on
  every row.

Rules are written against the snake_cased output of the suggested pipeline.
Both files are commented so every choice can be reviewed; judgement calls
(imputing missing values, capping instead of flagging outliers) are left as
commented-out alternatives rather than applied silently.
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from typing import Any

import numpy as np
import pandas as pd
import yaml

from .clean import _missing_frame, _missing_series, parse_number_column, snake_case_columns
from .dates import parse_dates
from .profile import ColumnProfile, ProfileReport, profile_dataframe

EMAIL_REGEX = r"^[^@\s]+@[^@\s]+\.[^@\s]+$"
E164_REGEX = r"^\+[1-9]\d{6,14}(;ext=\d+)?$"


@dataclass
class SuggestedStep:
    step: dict[str, Any]
    comment: list[str] = field(default_factory=list)
    active: bool = True
    core: bool = True  # part of the safe default pass used by `cleankit clean`


@dataclass
class Suggestion:
    name: str
    source: str
    profile: ProfileReport
    steps: list[SuggestedStep]
    rules: dict[str, Any]
    rule_comments: dict[str, list[str]] = field(default_factory=dict)

    @property
    def pipeline(self) -> dict[str, Any]:
        """The active steps as a pipeline config (what ``load_pipeline`` returns)."""
        return {"name": self.name, "steps": [s.step for s in self.steps if s.active]}

    def core_pipeline(self) -> dict[str, Any]:
        return {
            "name": self.name,
            "steps": [s.step for s in self.steps if s.active and s.core],
        }

    def steps_yaml(self) -> str:
        out = [
            f"# Starter cleaning pipeline for {self.source}, generated by `cleankit suggest`.",
            f"# Profiled {self.profile.n_rows} rows x {self.profile.n_cols} columns, "
            f"{self.profile.n_issues} suspected issues.",
            "# Review every step; commented-out blocks are judgement calls left to you.",
            "# Run it with:",
            f"#   cleankit run-pipeline {self.source} --steps steps.yaml --out cleaned.csv",
            "",
            f"name: {_scalar(self.name)}",
            "",
            "steps:",
        ]
        for s in self.steps:
            out.append("")
            for line in s.comment:
                out.append(f"  # {line}" if line else "  #")
            body = _emit_mapping_item(s.step, indent=2)
            if not s.active:
                body = [
                    "  # " + line[2:] if line.startswith("  ") else "# " + line
                    for line in body
                ]
            out.extend(body)
        return "\n".join(out) + "\n"

    def rules_yaml(self) -> str:
        out = [
            f"# Validation rules for the cleaned output of {self.source}, generated by",
            "# `cleankit suggest`. Column names are the snake_cased names the pipeline",
            "# writes. Ranges come from the observed quartiles (3x IQR, rounded out),",
            "# so values the profiler flagged as outliers are expected to fail.",
            "# Run with:",
            "#   cleankit validate cleaned.csv --rules rules.yaml",
            "",
            "columns:" if self.rules["columns"] else "columns: {}",
        ]
        for col, spec in self.rules["columns"].items():
            for line in self.rule_comments.get(col, []):
                out.append(f"  # {line}")
            out.append(f"  {_key(col)}:")
            for rule, value in spec.items():
                if isinstance(value, dict):
                    out.append(f"    {rule}:")
                    for k, v in value.items():
                        out.append(f"      {k}: {_scalar(v)}")
                else:
                    out.append(f"    {rule}: {_value(value)}")
        out.append("")
        if self.rules["checks"]:
            out.append("# Cross-field checks that held on every row of the sample.")
            out.append("checks:")
            for check in self.rules["checks"]:
                out.extend(_emit_mapping_item(check, indent=2))
        else:
            out.append("checks: []")
        return "\n".join(out) + "\n"


# ---------------------------------------------------------------------------
# YAML emission (small, predictable, round-trips through yaml.safe_load)
# ---------------------------------------------------------------------------


def _scalar(value: Any) -> str:
    text = yaml.safe_dump([value], default_flow_style=True, allow_unicode=True, width=10_000)
    return text.strip()[1:-1]


def _key(value: Any) -> str:
    return _scalar(str(value))


def _value(value: Any) -> str:
    if isinstance(value, (list, tuple)):
        return "[" + ", ".join(_scalar(v) for v in value) + "]"
    if isinstance(value, dict):
        return "{" + ", ".join(f"{_key(k)}: {_value(v)}" for k, v in value.items()) + "}"
    return _scalar(value)


def _emit_mapping_item(item: dict[str, Any], indent: int) -> list[str]:
    pad = " " * indent
    lines: list[str] = []
    first = True
    for k, v in item.items():
        prefix = f"{pad}- " if first else f"{pad}  "
        first = False
        if isinstance(v, dict) and v:
            lines.append(f"{prefix}{_key(k)}:")
            for kk, vv in v.items():
                lines.append(f"{pad}    {_key(kk)}: {_value(vv)}")
        else:
            lines.append(f"{prefix}{_key(k)}: {_value(v)}")
    return lines


